CREATE TABLE `alarms` (
	`id` text PRIMARY KEY NOT NULL,
	`label` text NOT NULL,
	`latitude` real NOT NULL,
	`longitude` real NOT NULL,
	`place_name` text NOT NULL,
	`radius` integer DEFAULT 500 NOT NULL,
	`enabled` integer DEFAULT true NOT NULL,
	`repeat` integer DEFAULT true NOT NULL,
	`repeat_days` text DEFAULT '[1,2,3,4,5]' NOT NULL,
	`window_start` text,
	`window_end` text,
	`sound_id` text DEFAULT 'default' NOT NULL,
	`vibrate` integer DEFAULT true NOT NULL,
	`created_at` integer NOT NULL,
	`updated_at` integer NOT NULL,
	`last_fired_at` integer,
	CONSTRAINT "alarms_label_not_empty" CHECK(length(trim("alarms"."label")) > 0),
	CONSTRAINT "alarms_place_name_not_empty" CHECK(length(trim("alarms"."place_name")) > 0),
	CONSTRAINT "alarms_latitude_range" CHECK("alarms"."latitude" >= -90 AND "alarms"."latitude" <= 90),
	CONSTRAINT "alarms_longitude_range" CHECK("alarms"."longitude" >= -180 AND "alarms"."longitude" <= 180),
	CONSTRAINT "alarms_radius_range" CHECK("alarms"."radius" >= 200 AND "alarms"."radius" <= 2000),
	CONSTRAINT "alarms_enabled_boolean" CHECK("alarms"."enabled" IN (0, 1)),
	CONSTRAINT "alarms_repeat_boolean" CHECK("alarms"."repeat" IN (0, 1)),
	CONSTRAINT "alarms_vibrate_boolean" CHECK("alarms"."vibrate" IN (0, 1)),
	CONSTRAINT "alarms_repeat_schedule" CHECK(("alarms"."repeat" = 1 AND "alarms"."repeat_days" <> '[]' AND "alarms"."window_start" GLOB '[0-2][0-9]:[0-5][0-9]' AND CAST(substr("alarms"."window_start", 1, 2) AS INTEGER) <= 23 AND "alarms"."window_end" GLOB '[0-2][0-9]:[0-5][0-9]' AND CAST(substr("alarms"."window_end", 1, 2) AS INTEGER) <= 23 AND (CAST(substr("alarms"."window_start", 1, 2) AS INTEGER) * 60 + CAST(substr("alarms"."window_start", 4, 2) AS INTEGER)) < (CAST(substr("alarms"."window_end", 1, 2) AS INTEGER) * 60 + CAST(substr("alarms"."window_end", 4, 2) AS INTEGER))) OR ("alarms"."repeat" = 0 AND "alarms"."repeat_days" = '[]' AND "alarms"."window_start" IS NULL AND "alarms"."window_end" IS NULL))
);
